"""Task-table loading, seed derivation and stage selection (spec §2.3).

The table itself is a build-time artefact (``tasks.json``, generated by ``build_task_table.py``); this
module only reads it and derives the deterministic per-cell coordinates.  A damaged or stale table is
a hard error — the benchmark must never silently shrink to a subset of the tasks.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any, Mapping, Sequence

MODULE_DIR = Path(__file__).resolve().parent
DEFAULT_TASKS_PATH = MODULE_DIR / "tasks.json"

#: spec §2.1: the registry holds exactly 125 task classes; anything else is a stale table.
EXPECTED_TASK_COUNT = 125
#: spec §0 口径 2: 240s episode budget (mirrors ``build_task_table.EPISODE_MAX_TIME_MS_DEFAULT``).
EPISODE_MAX_TIME_MS_DEFAULT = 240000

#: spec §2.3: pilot = exactly these 10 subdomains (≥5 families, ≥1 visual); missing from the table is fatal.
PILOT_SUBDOMAINS: tuple[str, ...] = (
    "click-test",
    "click-button",
    "click-checkboxes",
    "enter-text",
    "enter-password",
    "focus-text",
    "login-user",
    "use-autocomplete",
    "email-inbox-forward-nl",
    "visual-addition",
)

STAGES: tuple[str, ...] = ("pilot", "full")
STAGE_RUNS: Mapping[str, int] = {"pilot": len(PILOT_SUBDOMAINS), "full": EXPECTED_TASK_COUNT}


class BenchmarkError(RuntimeError):
    """Unrecoverable harness error (unusable task table, unknown stage, budget breach, bad pilot set)."""


def load_tasks(path: str | Path | None = None) -> list[dict[str, Any]]:
    """Read ``tasks.json`` and validate it: 125 rows with unique ``task_id`` (spec §2.3)."""
    tasks_path = Path(path) if path is not None else DEFAULT_TASKS_PATH
    try:
        payload = json.loads(tasks_path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise BenchmarkError(f"cannot read task table {tasks_path}: {exc}") from exc
    except ValueError as exc:
        raise BenchmarkError(f"task table {tasks_path} is not valid json: {exc}") from exc
    if not isinstance(payload, Mapping) or not isinstance(payload.get("tasks"), list):
        raise BenchmarkError(f"task table {tasks_path} has no 'tasks' array")
    tasks = [dict(task) for task in payload["tasks"] if isinstance(task, Mapping)]
    if len(tasks) != EXPECTED_TASK_COUNT:
        raise BenchmarkError(f"task table {tasks_path} holds {len(tasks)} tasks, expected {EXPECTED_TASK_COUNT}")
    ids = [str(task.get("task_id")) for task in tasks]
    if len(set(ids)) != len(ids):
        raise BenchmarkError(f"task table {tasks_path} has duplicate task ids")
    return tasks


def check_pilot_subdomains(tasks: Sequence[Mapping[str, Any]]) -> None:
    """Fail fast when the upstream registry renamed/removed a pilot task (spec §2.3: no silent shrink)."""
    known = {str(task["subdomain"]) for task in tasks}
    missing = [subdomain for subdomain in PILOT_SUBDOMAINS if subdomain not in known]
    if missing:
        raise BenchmarkError(f"pilot subdomains missing from the task table: {missing}")


def select_stage(stage: str, tasks: Sequence[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """Cells of one stage, in a deterministic order (``pilot`` = §2.3 list, ``full`` = table order)."""
    if stage == "pilot":
        check_pilot_subdomains(tasks)
        by_subdomain = {str(task["subdomain"]): dict(task) for task in tasks}
        return [by_subdomain[subdomain] for subdomain in PILOT_SUBDOMAINS]
    if stage == "full":
        return [dict(task) for task in tasks]
    raise BenchmarkError(f"unknown stage: {stage!r} (expected one of {STAGES})")


def derive_seed(exp_id: str, task_id: str) -> int:
    """Deterministic per-cell seed (spec §2.3): ``int(sha1(f"{exp_id}:miniwob:{task_id}")[:8], 16)``."""
    digest = hashlib.sha1(f"{exp_id}:miniwob:{task_id}".encode("utf-8")).hexdigest()
    return int(digest[:8], 16)


def make_run_id(subdomain: str, seed: int) -> str:
    """``miniwob__<subdomain>__s<seed>`` (spec §2.3); the seed must already be final."""
    return f"miniwob__{subdomain}__s{seed}"
